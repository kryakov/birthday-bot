def validate_birth_date(text: str | None) -> tuple[int, int] | None:
    if text is None:
        return None

    text = text.strip()
    if re.fullmatch(r"[0-9]{2}\.[0-9]{2}", text) is None:
        return None

    day, month = map(int, text.split("."))
    try:
        date(2000, month, day)
    except ValueError:
        return None

    return day, month


def get_zodiac_sign(day: int, month: int) -> str:
    date(2000, month, day)
    for start_month, start_day, sign in reversed(ZODIAC_STARTS):
        if (month, day) >= (start_month, start_day):
            return sign
    return "Козерог"
